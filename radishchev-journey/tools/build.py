#!/usr/bin/env python3
"""Rebuilds everything that depends on the voice's word times.

  python3 tools/build.py

Reads assets/transcript.json (the real voiceover's words, one entry per script word, same order)
or, until that exists, assets/transcript.estimate.json. Writes assets/times.js, index.html and
compositions/captions.html, and sets each scene's clip duration. Scenes read their anchors from
times.js as w(<word index>), so a new transcript retimes the whole film.
"""
import json, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
FPS = 30
real = os.path.exists("assets/transcript.json")
words = json.load(open("assets/transcript.json" if real else "assets/transcript.estimate.json", encoding="utf-8"))
script = open("SCRIPT.md", encoding="utf-8").read().split("\n", 1)[1].split()
assert len(words) == len(script) == 194, (len(words), len(script))
W = [w["start"] for w in words]; E = [w["end"] for w in words]

# scene id -> first word index
SCENES = [("s1", 0), ("s2", 14), ("s3", 42), ("s4", 52), ("s5", 82), ("s6", 107), ("s7", 122), ("s8", 140),
          ("s9", 162), ("s10", 181)]
LEAD = {"s7": 0.05}   # how far a scene starts before its first word (default 0.3 s)
S = {sid: (0 if i == 0 else round(W[first] - LEAD.get(sid, 0.3), 2)) for i, (sid, first) in enumerate(SCENES)}
ends = [S[sid] for sid, _ in SCENES[1:]] + [round(E[-1] + 1.9, 2)]
D = {sid: round(ends[i] - S[sid], 2) for i, (sid, _) in enumerate(SCENES)}
S["s11"] = ends[-1]; D["s11"] = 3.0
TOTAL = round(S["s11"] + D["s11"], 2)

open("assets/times.js", "w").write(
    "/* generated by tools/build.py: word starts (W) and ends (E), scene starts (S) and lengths (D) */\n"
    "window.DT = " + json.dumps({"W": W, "E": E, "S": S, "D": D, "real": real}) + ";\n")

for sid in S:
    p = f"compositions/{sid}.html"
    if os.path.exists(p):
        h = open(p, encoding="utf-8").read()
        h = re.sub(rf'(id="{sid}-wrap" class="clip" data-start="0" data-duration=")[\d.]+', rf"\g<1>{D[sid]}", h)
        open(p, "w", encoding="utf-8").write(h)

# ---- Lottie: assets/lottie/*.json -> assets/lottie/data.js (window.LOTTIE), so scenes load them without a fetch
import glob
lot = {os.path.basename(f)[:-5]: json.load(open(f)) for f in sorted(glob.glob("assets/lottie/*.json"))}
open("assets/lottie/data.js", "w").write("window.LOTTIE = " + json.dumps(lot, separators=(",", ":")) + ";\n")

# ---- captions: script spelling, transcript times
groups, cur = [], []
def flush():
    global cur
    if cur: groups.append(cur); cur = []
for i, tok in enumerate(script):
    cur.append(i)
    chars = sum(len(script[j]) for j in cur) + len(cur) - 1
    nxt = len(script[i + 1]) if i + 1 < len(script) else 0
    if re.search(r"[.؟!…:،]$", tok) or len(cur) >= 5 or chars + 1 + nxt > 24: flush()
flush()
# a lone short word joins its neighbour when they share a sentence
merged = []
for g in groups:
    if merged and len(g) == 1 and not re.search(r"[.؟!…]$", script[merged[-1][-1]]) and \
       sum(len(script[j]) for j in merged[-1] + g) + len(merged[-1]) <= 26:
        merged[-1] = merged[-1] + g
    else: merged.append(g)
groups = merged
caps = []
for n, g in enumerate(groups):
    text = " ".join(script[j] for j in g)
    text = re.sub(r"[.،:]", "", text).strip()
    start = max(0.12, W[g[0]] - 0.06)
    nxt = W[groups[n + 1][0]] - 0.06 if n + 1 < len(groups) else E[g[-1]] + 0.5
    end = nxt if nxt - E[g[-1]] < 0.7 else E[g[-1]] + 0.35
    caps.append(f'    <div id="cap-{n:02d}" class="clip cap" data-start="{start:.2f}" data-duration="{end - start:.2f}"><span>{text}</span></div>')
CAP_END = round(E[-1] + 0.6, 2)
open("compositions/captions.html", "w", encoding="utf-8").write(f'''<template>
  <style>
    @font-face {{ font-family: "Noto Kufi Arabic"; src: url("assets/fonts/NotoKufiArabic.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; }}
    .cap {{ position: absolute; left: 60px; width: 960px; top: 1212px; height: 104px; text-align: center; direction: rtl; }}
    .cap span {{ display: inline-block; padding: 6px 30px 10px; background: #0c1a30; color: #F4F6F9; border: 5px solid #F4F6F9; border-radius: 14px; font-family: "Noto Kufi Arabic", sans-serif; font-weight: 800; font-size: 50px; line-height: 78px; white-space: nowrap; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
{chr(10).join(caps)}
  </div>
  <script>
    window.__timelines["captions"] = gsap.timeline({{ paused: true }});
  </script>
</template>
''')

# ---- sound effects: (scene, word index, offset from that word, file in sfx-library, volume)
# The picture each one belongs to is at w(word)+offset in that scene's script.
SFX = json.load(open("tools/sfx.json")) if os.path.exists("tools/sfx.json") else []
man = json.load(open("../sfx-library/manifest.json")); man = man.get("sounds", man)
byfile = {v["file"]: v for v in man.values() if isinstance(v, dict)}
audio = []; busy = {}
os.makedirs("assets/sfx", exist_ok=True)
for n, (sid, wi, off, f, vol, *rest) in enumerate(SFX):
    info = byfile[f]; name = os.path.basename(f)
    if not os.path.exists("assets/sfx/" + name): shutil.copy("../sfx-library/" + f, "assets/sfx/" + name)
    t = W[wi] + off
    riser = rest and rest[0] == "riser"
    start = t - info["duration"] if riser else t - info["peak_at"] + 1 / FPS
    start = max(0, start); track = 11
    while busy.get(track, -1) > start: track += 1   # overlapping effects go on separate tracks
    busy[track] = start + info["duration"]
    audio.append(f'      <audio id="sfx-{n + 1:02d}" class="clip" src="assets/sfx/{name}" data-start="{start:.3f}" data-duration="{info["duration"]}" data-track-index="{track}" data-volume="{vol}"></audio>')

hosts = "\n".join(
    f'      <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" data-start="{S[sid]}" data-duration="{D[sid]}" data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920" style="z-index:2"></div>'
    for sid in S)
voice = '      <audio id="voiceover" class="clip" src="assets/voiceover.mp3" data-start="0" data-track-index="10" data-volume="1"></audio>\n' if os.path.exists("assets/voiceover.mp3") else ""
open("index.html", "w", encoding="utf-8").write(f'''<!doctype html>
<!-- generated by tools/build.py: edit that file, not this one -->
<html lang="ar" data-resolution="portrait"
  data-composition-variables='[{{"id":"navy","type":"color","label":"Ground navy","default":"#13294B"}},{{"id":"gold","type":"color","label":"Punch gold","default":"#CEA532"}},{{"id":"light","type":"color","label":"Text light","default":"#F4F6F9"}}]'>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/times.js"></script>
    <script src="assets/vendor/lottie_svg.min.js"></script>
    <script src="assets/lottie/data.js"></script>
    <script src="assets/kit.js"></script>
    <style>
      @font-face {{ font-family: "Lalezar"; src: url("assets/fonts/Lalezar-Regular.ttf"); font-weight: 400; }}
      @font-face {{ font-family: "Noto Kufi Arabic"; src: url("assets/fonts/NotoKufiArabic.ttf"); font-weight: 100 900; }}
      :root {{ --navy: #13294B; --navy2: #1C385A; --gold: #CEA532; --light: #F4F6F9; --ink: #0c1a30; --wood: #8a5a33; --wood2: #6b4226; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: var(--navy); }}
      /* shared scene styles */
      .stage {{ position: absolute; left: 0; top: 0; width: 1080px; height: 1920px; }}
      .kufi {{ font-family: "Noto Kufi Arabic", sans-serif; direction: rtl; }}
      .disp {{ font-family: "Lalezar", sans-serif; direction: rtl; }}
      .count {{ position: absolute; left: 90px; right: 90px; top: 178px; text-align: center; font-family: "Noto Kufi Arabic", sans-serif; font-weight: 800; font-size: 50px; line-height: 1.3; color: #9fb4d0; direction: rtl; }}
      .ttl {{ position: absolute; left: 60px; right: 60px; top: 236px; text-align: center; font-family: "Lalezar", sans-serif; font-size: 138px; line-height: 1.15; color: var(--light); direction: rtl; }}
      .plate {{ position: absolute; text-align: center; font-family: "Lalezar", sans-serif; direction: rtl; color: var(--ink); background: var(--gold); border: 9px solid var(--ink); outline: 7px solid var(--gold); outline-offset: 9px; border-radius: 14px; line-height: 1.2; }}
      .card {{ position: absolute; text-align: center; direction: rtl; color: var(--ink); background: var(--light); border: 7px solid var(--ink); border-radius: 12px; }}
      .sign {{ position: absolute; text-align: center; direction: rtl; color: var(--light); background: #a8703f; border: 7px solid var(--ink); border-radius: 12px; font-family: "Lalezar", sans-serif; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{TOTAL}" data-width="1080" data-height="1920">
{hosts}
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{CAP_END}" data-track-index="2" data-track-kind="captions" data-width="1080" data-height="1920" style="z-index:5"></div>
{voice}{chr(10).join(audio)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
''')
print("words:", "voice" if real else "ESTIMATE", "| total", TOTAL, "s |", len(caps), "captions |", len(audio), "sfx")
for sid in S: print(f"  {sid:4} {S[sid]:7.2f} +{D[sid]:.2f}")
